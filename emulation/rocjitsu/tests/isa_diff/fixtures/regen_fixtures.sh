# Regenerate executor.inc from executor.asm. Each section is `=== name processor`; it is
# assembled for that processor and recorded as instruction words, so the tests never run an
# assembler. Usage: regen_fixtures.sh [llvm-mc] [llvm-objcopy]
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
mc=${1:-/opt/rocm/llvm/bin/llvm-mc}
objcopy=${2:-/opt/rocm/llvm/bin/llvm-objcopy}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
src="$here/executor.asm"
out="$here/executor.inc"
{
  echo "// Generated by regen_fixtures.sh from executor.asm. Do not edit."
  echo "// Assembler: $("$mc" --version | grep -m1 -i 'llvm version' | sed 's/^ *//')"
} > "$out"
grep -E '^=== ' "$src" | while read -r _ name cpu; do
  awk -v n="$name" '
    /^=== / { on = ($2 == n); next }
    on && !/^#/ && NF { print }
  ' "$src" > "$tmp/$name.s"
  log=$("$mc" -triple=amdgcn-amd-amdhsa -mcpu="$cpu" -filetype=obj "$tmp/$name.s" \
    -o "$tmp/$name.o" 2>&1) || { echo "$log" >&2; exit 1; }
  # llvm-mc only warns about an unknown processor and assembles for a generic one.
  if grep -q "not a recognized processor" <<<"$log"; then
    echo "$mc does not know $cpu" >&2
    exit 1
  fi
  "$objcopy" -O binary --only-section=.text "$tmp/$name.o" "$tmp/$name.bin"
  {
    echo ""
    echo "// $cpu"
    sed 's|^|// |' "$tmp/$name.s"
    printf 'inline const std::vector<uint32_t> k_%s = {' "$name"
    od -An -v -t x4 -w4 "$tmp/$name.bin" | awk '{printf "%s0x%s", (NR>1?", ":""), $1}'
    echo "};"
  } >> "$out"
done
echo "wrote $out"
